-- ------------------------------------------------------------------------------
-- 2. TABELAS CORE
-- ------------------------------------------------------------------------------

CREATE TABLE CLINICA (
    id_clinica NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) NOT NULL,
    nome       VARCHAR2(100) NOT NULL,
    cnpj       VARCHAR2(20)  NOT NULL,
    logradouro VARCHAR2(200)
);

ALTER TABLE CLINICA ADD CONSTRAINT CLINICA_PK      PRIMARY KEY (id_clinica);
ALTER TABLE CLINICA ADD CONSTRAINT CLINICA_CNPJ_UK UNIQUE      (cnpj);

COMMENT ON TABLE CLINICA IS 'Unidade de atendimento da rede Clyvo Vet (CORE da operacao clinica).';
COMMENT ON COLUMN CLINICA.id_clinica IS 'Chave primaria da clinica, gerada por identity a partir de 100.';
COMMENT ON COLUMN CLINICA.nome IS 'Nome fantasia da unidade.';
COMMENT ON COLUMN CLINICA.cnpj IS 'CNPJ unico da unidade.';
COMMENT ON COLUMN CLINICA.logradouro IS 'Endereco da unidade de atendimento.';

CREATE TABLE TUTOR (
    id_tutor NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) NOT NULL,
    nome     VARCHAR2(100) NOT NULL,
    cpf      VARCHAR2(14)  NOT NULL,
    telefone VARCHAR2(20)
);

ALTER TABLE TUTOR ADD CONSTRAINT TUTOR_PK     PRIMARY KEY (id_tutor);
ALTER TABLE TUTOR ADD CONSTRAINT TUTOR_CPF_UK UNIQUE      (cpf);

COMMENT ON TABLE TUTOR IS 'Tutor (responsavel legal) do pet. Tabela CORE do CRUD, relacionada com PET.';
COMMENT ON COLUMN TUTOR.id_tutor IS 'Chave primaria do tutor, gerada por identity a partir de 100.';
COMMENT ON COLUMN TUTOR.nome IS 'Nome completo do tutor.';
COMMENT ON COLUMN TUTOR.cpf IS 'CPF unico do tutor.';
COMMENT ON COLUMN TUTOR.telefone IS 'Telefone de contato para comunicacao clinica.';

CREATE TABLE VETERINARIO (
    id_veterinario NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) NOT NULL,
    nome           VARCHAR2(100) NOT NULL,
    crmv           VARCHAR2(20)  NOT NULL,
    telefone       VARCHAR2(20)
);

ALTER TABLE VETERINARIO ADD CONSTRAINT VETERINARIO_PK      PRIMARY KEY (id_veterinario);
ALTER TABLE VETERINARIO ADD CONSTRAINT VETERINARIO_CRMV_UK UNIQUE      (crmv);

COMMENT ON TABLE VETERINARIO IS 'Medico veterinario habilitado a realizar consultas na rede.';
COMMENT ON COLUMN VETERINARIO.id_veterinario IS 'Chave primaria do veterinario, gerada por identity a partir de 100.';
COMMENT ON COLUMN VETERINARIO.nome IS 'Nome completo do profissional.';
COMMENT ON COLUMN VETERINARIO.crmv IS 'Registro profissional CRMV (unico).';
COMMENT ON COLUMN VETERINARIO.telefone IS 'Telefone de contato do profissional.';

CREATE TABLE PET (
    id_pet   NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) NOT NULL,
    id_tutor NUMBER        NOT NULL,
    nome     VARCHAR2(100) NOT NULL,
    especie  VARCHAR2(50)  NOT NULL,
    cor      VARCHAR2(30),
    idade    NUMBER(3),
    peso     NUMBER(5,2)
);

ALTER TABLE PET ADD CONSTRAINT PET_PK PRIMARY KEY (id_pet);

COMMENT ON TABLE PET IS 'Animal sob cuidados da clinica. Tabela CORE do CRUD, filha de TUTOR.';
COMMENT ON COLUMN PET.id_pet IS 'Chave primaria do pet, gerada por identity a partir de 100.';
COMMENT ON COLUMN PET.id_tutor IS 'Chave estrangeira para o tutor responsavel.';
COMMENT ON COLUMN PET.nome IS 'Nome de identificacao do animal.';
COMMENT ON COLUMN PET.especie IS 'Especie do animal (ex.: Cachorro, Gato).';
COMMENT ON COLUMN PET.cor IS 'Cor/pelagem do animal.';
COMMENT ON COLUMN PET.idade IS 'Idade aproximada em anos.';
COMMENT ON COLUMN PET.peso IS 'Peso do animal em quilogramas.';

CREATE TABLE PRONTUARIO (
    id_prontuario NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) NOT NULL,
    diagnostico   VARCHAR2(500),
    data_registro DATE
);

ALTER TABLE PRONTUARIO ADD CONSTRAINT PRONTUARIO_PK PRIMARY KEY (id_prontuario);

COMMENT ON TABLE PRONTUARIO IS 'Registro clinico gerado a partir do atendimento.';
COMMENT ON COLUMN PRONTUARIO.id_prontuario IS 'Chave primaria do prontuario, gerada por identity a partir de 100.';
COMMENT ON COLUMN PRONTUARIO.diagnostico IS 'Descricao do diagnostico e conduta.';
COMMENT ON COLUMN PRONTUARIO.data_registro IS 'Data em que o prontuario foi registrado.';

-- Tabela transacional da aplicacao.
-- status: Agendada | Realizada | Cancelada
CREATE TABLE CONSULTA (
    id_consulta    NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) NOT NULL,
    id_veterinario NUMBER        NOT NULL,
    id_pet         NUMBER        NOT NULL,
    id_clinica     NUMBER        NOT NULL,
    id_prontuario  NUMBER,
    data_consulta  DATE          NOT NULL,
    status         VARCHAR2(20),
    valor          NUMBER(10,2)  DEFAULT 0
);

ALTER TABLE CONSULTA ADD CONSTRAINT CONSULTA_PK        PRIMARY KEY (id_consulta);
ALTER TABLE CONSULTA ADD CONSTRAINT CONSULTA_VALOR_CK  CHECK (valor >= 0);
ALTER TABLE CONSULTA ADD CONSTRAINT CONSULTA_STATUS_CK CHECK (status IN ('Agendada','Realizada','Cancelada'));

ALTER TABLE PET      ADD CONSTRAINT fk_pet_tutor    FOREIGN KEY (id_tutor)      REFERENCES TUTOR (id_tutor);
ALTER TABLE CONSULTA ADD CONSTRAINT fk_cons_clinica FOREIGN KEY (id_clinica)    REFERENCES CLINICA (id_clinica);
ALTER TABLE CONSULTA ADD CONSTRAINT fk_cons_pet     FOREIGN KEY (id_pet)        REFERENCES PET (id_pet);
ALTER TABLE CONSULTA ADD CONSTRAINT fk_cons_pront   FOREIGN KEY (id_prontuario) REFERENCES PRONTUARIO (id_prontuario);
ALTER TABLE CONSULTA ADD CONSTRAINT fk_cons_vet     FOREIGN KEY (id_veterinario) REFERENCES VETERINARIO (id_veterinario);

COMMENT ON TABLE CONSULTA IS 'Agendamento que integra pet, veterinario, clinica e prontuario.';
COMMENT ON COLUMN CONSULTA.id_consulta IS 'Chave primaria da consulta, gerada por identity a partir de 100.';
COMMENT ON COLUMN CONSULTA.id_veterinario IS 'Veterinario responsavel pelo atendimento.';
COMMENT ON COLUMN CONSULTA.id_pet IS 'Pet atendido na consulta.';
COMMENT ON COLUMN CONSULTA.id_clinica IS 'Clinica onde a consulta ocorre.';
COMMENT ON COLUMN CONSULTA.id_prontuario IS 'Prontuario vinculado (opcional).';
COMMENT ON COLUMN CONSULTA.data_consulta IS 'Data do atendimento.';
COMMENT ON COLUMN CONSULTA.status IS 'Situacao: Agendada, Realizada ou Cancelada.';
COMMENT ON COLUMN CONSULTA.valor IS 'Valor do atendimento. A API .NET nao mapeia esta coluna; o DEFAULT 0 cobre os inserts do EF.';

-- ------------------------------------------------------------------------------
-- 3. INDICES NAS FOREIGN KEYS
-- ------------------------------------------------------------------------------

CREATE INDEX ix_pet_tutor         ON PET      (id_tutor);
CREATE INDEX ix_cons_pet          ON CONSULTA (id_pet);
CREATE INDEX ix_cons_clinica      ON CONSULTA (id_clinica);
CREATE INDEX ix_cons_vet          ON CONSULTA (id_veterinario);
CREATE INDEX ix_cons_prontuario   ON CONSULTA (id_prontuario);
CREATE INDEX ix_cons_data_clinica ON CONSULTA (id_clinica, data_consulta);

-- ------------------------------------------------------------------------------
-- 4. VIEW DE LEITURA
-- ------------------------------------------------------------------------------

CREATE OR REPLACE VIEW vw_consulta_detalhe AS
SELECT cons.id_consulta,
       cons.data_consulta,
       cons.status,
       cons.valor,
       p.id_pet,
       p.nome     AS pet,
       p.especie,
       p.idade,
       p.peso,
       t.id_tutor,
       t.nome     AS tutor,
       t.telefone AS telefone_tutor,
       v.id_veterinario,
       v.nome     AS veterinario,
       v.crmv,
       cl.id_clinica,
       cl.nome    AS clinica,
       pr.id_prontuario,
       pr.diagnostico
  FROM CONSULTA cons
  JOIN PET         p  ON p.id_pet         = cons.id_pet
  JOIN TUTOR       t  ON t.id_tutor       = p.id_tutor
  JOIN VETERINARIO v  ON v.id_veterinario = cons.id_veterinario
  JOIN CLINICA     cl ON cl.id_clinica    = cons.id_clinica
  LEFT JOIN PRONTUARIO pr ON pr.id_prontuario = cons.id_prontuario;


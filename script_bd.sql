SET DEFINE OFF;

-- ------------------------------------------------------------------------------
-- 1. LIMPEZA (permite reexecutar o arquivo do zero)
-- ------------------------------------------------------------------------------
BEGIN
    FOR r IN (
        SELECT  1 AS ordem, 'DROP VIEW vw_consulta_detalhe'                 AS cmd FROM DUAL UNION ALL
        SELECT  2, 'DROP TABLE CONSULTA CASCADE CONSTRAINTS'                FROM DUAL UNION ALL
        SELECT  3, 'DROP TABLE PET CASCADE CONSTRAINTS'                     FROM DUAL UNION ALL
        SELECT  4, 'DROP TABLE PRONTUARIO CASCADE CONSTRAINTS'              FROM DUAL UNION ALL
        SELECT  5, 'DROP TABLE VETERINARIO CASCADE CONSTRAINTS'             FROM DUAL UNION ALL
        SELECT  6, 'DROP TABLE CLINICA CASCADE CONSTRAINTS'                 FROM DUAL UNION ALL
        SELECT  7, 'DROP TABLE TUTOR CASCADE CONSTRAINTS'                   FROM DUAL
        ORDER BY 1
    ) LOOP
        BEGIN
            EXECUTE IMMEDIATE r.cmd;
        EXCEPTION
            WHEN OTHERS THEN NULL;
        END;
    END LOOP;
END;
